"""Stage 4: Narration generation, exact duration probing, SRT subtitles, and music."""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pipeline.cache import compute_cache_key, file_sha256, is_cache_valid, load_manifest, save_manifest
from pipeline.config import PipelineConfig
from pipeline.logger import RunLogEntry, append_run_log
from pipeline.providers.gemini_client import (
    generate_gemini_tts_narration,
    generate_placeholder_narration,
    measure_wav_duration_sec,
)
from pipeline.providers.local_audio import generate_local_tts_narration
from pipeline.providers.music_adapter import MusicTrackResult, resolve_music_track
from pipeline.validate import wrap_subtitle_text


@dataclass(frozen=True)
class AudioStageOutput:
    """Outputs generated by Stage 4."""

    narration_paths: dict[str, Path]
    measured_durations: dict[str, float]
    shot_timings: list[dict[str, Any]]
    srt_path: Path
    music_result: MusicTrackResult


def format_srt_timestamp(seconds: float) -> str:
    """Format seconds as HH:MM:SS,mmm for SubRip (.srt)."""
    total_ms = max(0, int(round(seconds * 1000)))
    hours = total_ms // 3_600_000
    minutes = (total_ms % 3_600_000) // 60_000
    secs = (total_ms % 60_000) // 1000
    ms = total_ms % 1000
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{ms:03d}"


def build_subtitles_srt(
    shots: list[dict[str, Any]],
    measured_durations: dict[str, float],
    output_srt_path: Path,
    lead_in_sec: float = 0.25,
    min_tail_pad_sec: float = 0.6,
) -> tuple[Path, list[dict[str, Any]]]:
    """Build synchronized .srt cues from actual measured narration durations."""
    cues: list[str] = []
    timings: list[dict[str, Any]] = []
    cursor = 0.0
    cue_index = 1

    for shot in shots:
        shot_id = shot["shot_id"]
        target_dur = float(shot["duration_sec"])
        audio_dur = float(measured_durations.get(shot_id, target_dur))
        effective_shot_dur = max(target_dur, round(audio_dur + lead_in_sec + min_tail_pad_sec, 3))

        text = shot["narration"]["text"]
        chunks = wrap_subtitle_text(text)
        speak_start = cursor + lead_in_sec
        speak_end = speak_start + audio_dur

        if chunks:
            chunk_dur = audio_dur / len(chunks)
            for idx, chunk in enumerate(chunks):
                c_start = speak_start + idx * chunk_dur
                c_end = speak_start + (idx + 1) * chunk_dur
                cues.append(
                    f"{cue_index}\n"
                    f"{format_srt_timestamp(c_start)} --> {format_srt_timestamp(c_end)}\n"
                    f"{chunk}\n"
                )
                cue_index += 1

        timings.append(
            {
                "shot_id": shot_id,
                "shot_start_sec": round(cursor, 3),
                "shot_end_sec": round(cursor + effective_shot_dur, 3),
                "effective_shot_duration_sec": effective_shot_dur,
                "narration_start_sec": round(speak_start, 3),
                "narration_end_sec": round(speak_end, 3),
                "measured_audio_duration_sec": audio_dur,
            }
        )
        cursor += effective_shot_dur

    output_srt_path.parent.mkdir(parents=True, exist_ok=True)
    output_srt_path.write_text("\n".join(cues).strip() + "\n", encoding="utf-8")
    return output_srt_path, timings


def run_stage4_audio(
    config: PipelineConfig,
    storyboard: dict[str, Any],
    run_id: str,
    shot_id_filter: str | None = None,
    force: bool = False,
) -> AudioStageOutput:
    """Generate/cache narration per shot, measure actual audio duration, build SRT & music."""
    config.ensure_directories()
    manifest_path = config.manifests_dir / "audio_manifest.json"
    manifest = load_manifest(manifest_path)

    narration_paths: dict[str, Path] = {}
    measured_durations: dict[str, float] = {}
    provider = config.narration_provider

    for idx, shot in enumerate(storyboard["shots"]):
        shot_id = shot["shot_id"]
        narration_cfg = shot["narration"]
        text = narration_cfg["text"]
        style = narration_cfg.get("style_instruction", "")
        out_path = config.narration_dir / f"{shot_id}.wav"

        if shot_id_filter and shot_id != shot_id_filter:
            if out_path.exists():
                narration_paths[shot_id] = out_path
                measured_durations[shot_id] = measure_wav_duration_sec(out_path)
            continue

        if provider == "gemini_tts":
            model_name = config.gemini_tts_model
        elif provider == "local_tts":
            model_name = "os_local_tts_v2"
        else:
            model_name = "placeholder_spoken_timing_cue"
        cache_key = compute_cache_key(
            {
                "stage": "stage4_narration",
                "provider": provider,
                "model": model_name,
                "voice": config.gemini_tts_voice if provider == "gemini_tts" else "local_default",
                "text": text,
                "style": style,
            }
        )

        cached = is_cache_valid(manifest, shot_id, cache_key, config.root_dir, force=force)
        if cached is not None:
            dur = measure_wav_duration_sec(cached)
            narration_paths[shot_id] = cached
            measured_durations[shot_id] = dur
            append_run_log(
                config.logs_path,
                RunLogEntry(
                    run_id=run_id,
                    stage="stage4_narration",
                    shot_id=shot_id,
                    provider=provider,
                    model=model_name,
                    status="cached",
                    cache_hit=True,
                    metadata={"measured_duration_sec": dur},
                ),
            )
            continue

        t0 = time.perf_counter()
        if provider == "gemini_tts":
            res = generate_gemini_tts_narration(
                config=config,
                text=text,
                style_instruction=style,
                output_path=out_path,
            )
        elif provider == "local_tts":
            res = generate_local_tts_narration(
                config=config,
                text=text,
                style_instruction=style,
                output_path=out_path,
                shot_index=idx,
            )
        else:
            res = generate_placeholder_narration(
                text=text,
                output_path=out_path,
                shot_index=idx,
            )
        elapsed = round(time.perf_counter() - t0, 3)

        manifest.setdefault("items", {})[shot_id] = {
            "cache_key": cache_key,
            "output_path": str(res.output_path.relative_to(config.root_dir)).replace("\\", "/"),
            "sha256": file_sha256(res.output_path),
            "provider": res.provider,
            "model": res.model,
            "duration_sec": res.duration_sec,
            "is_placeholder": res.is_placeholder,
        }
        save_manifest(manifest_path, manifest)

        narration_paths[shot_id] = res.output_path
        measured_durations[shot_id] = res.duration_sec
        append_run_log(
            config.logs_path,
            RunLogEntry(
                run_id=run_id,
                stage="stage4_narration",
                shot_id=shot_id,
                provider=res.provider,
                model=res.model,
                status="success",
                cache_hit=False,
                latency_sec=elapsed,
                estimated_cost_usd=res.estimated_cost_usd,
                metadata={
                    "measured_duration_sec": res.duration_sec,
                    "is_placeholder": res.is_placeholder,
                },
            ),
        )

    srt_path, shot_timings = build_subtitles_srt(
        storyboard["shots"],
        measured_durations,
        config.subtitles_dir / "subtitles.srt",
    )

    shots_total = sum(item["effective_shot_duration_sec"] for item in shot_timings)
    end_card_dur = float(storyboard["end_card"]["duration_sec"])
    music_target = round(shots_total + end_card_dur, 3)

    music_cfg = storyboard.get("music", {})
    music_model_tag = (
        "procedural_pentatonic_heritage_82bpm_v2"
        if config.music_provider == "local_score"
        else config.music_provider
    )
    music_cache_key = compute_cache_key(
        {
            "stage": "stage4_music",
            "provider": config.music_provider,
            "model": music_model_tag,
            "target_duration_sec": music_target,
            "music": music_cfg,
            "timings": shot_timings,
        }
    )
    prev_music = manifest.get("music", {})
    prev_music_path = (
        config.root_dir / prev_music["output_path"]
        if isinstance(prev_music, dict) and prev_music.get("output_path")
        else None
    )
    if (
        not force
        and isinstance(prev_music, dict)
        and prev_music.get("cache_key") == music_cache_key
        and prev_music_path is not None
        and prev_music_path.exists()
        and prev_music_path.stat().st_size > 0
    ):
        music_result = MusicTrackResult(
            output_path=prev_music_path,
            provider=str(prev_music.get("provider", config.music_provider)),
            model=str(prev_music.get("model", "cached")),
            duration_sec=measure_wav_duration_sec(prev_music_path),
            is_placeholder=bool(prev_music.get("is_placeholder", False)),
        )
        manifest["timings"] = shot_timings
        save_manifest(manifest_path, manifest)
        append_run_log(
            config.logs_path,
            RunLogEntry(
                run_id=run_id,
                stage="stage4_music",
                shot_id="soundtrack",
                provider=music_result.provider,
                model=music_result.model,
                status="cached",
                cache_hit=True,
                metadata={
                    "duration_sec": music_result.duration_sec,
                    "is_placeholder": music_result.is_placeholder,
                },
            ),
        )
    else:
        t0 = time.perf_counter()
        music_result = resolve_music_track(
            config,
            target_duration_sec=music_target,
            music_cfg=music_cfg,
            shot_timings=shot_timings,
        )
        music_elapsed = round(time.perf_counter() - t0, 3)

        manifest["timings"] = shot_timings
        manifest["music"] = {
            "cache_key": music_cache_key,
            "output_path": str(music_result.output_path.relative_to(config.root_dir)).replace("\\", "/"),
            "sha256": file_sha256(music_result.output_path),
            "provider": music_result.provider,
            "model": music_result.model,
            "duration_sec": music_result.duration_sec,
            "is_placeholder": music_result.is_placeholder,
        }
        save_manifest(manifest_path, manifest)

        append_run_log(
            config.logs_path,
            RunLogEntry(
                run_id=run_id,
                stage="stage4_music",
                shot_id="soundtrack",
                provider=music_result.provider,
                model=music_result.model,
                status="success",
                latency_sec=music_elapsed,
                metadata={
                    "duration_sec": music_result.duration_sec,
                    "is_placeholder": music_result.is_placeholder,
                },
            ),
        )

    return AudioStageOutput(
        narration_paths=narration_paths,
        measured_durations=measured_durations,
        shot_timings=shot_timings,
        srt_path=srt_path,
        music_result=music_result,
    )
